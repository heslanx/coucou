#!/bin/sh
# The prototype's copies of Koncluí's sounds, from the masters scripts/konclui/sounds.py writes:
# every app WAV and loop master -> AAC .m4a in <prototype>/koru/sounds/, and koru/sounds/loops.js, the -loop.m4a
# files as base64 so features/sounds.js can decode them for Web Audio on a file:// page (a fetch is refused there).
#   sh design/konclui/sound/tools/prototype-assets.sh /path/to/coucou/design/prototype
# afconvert stamps the container, so the .m4a bytes differ between runs; the decoded audio does not.
set -eu
ROOT=$(cd "$(dirname "$0")/../../../.." && pwd)
DEST=${1:?usage: prototype-assets.sh <design/prototype dir>}/koru/sounds
for f in "$ROOT"/NotchBuddy/Resources/sounds/*.wav "$ROOT"/design/konclui/sound/loops/*.wav; do
  afconvert -f m4af -d aac -q 127 "$f" "$DEST/$(basename "$f" .wav).m4a"
done
python3 - "$DEST" <<'EOF'
import base64, sys
from pathlib import Path
dest = Path(sys.argv[1])
rows = [f"'{p.stem}':'{base64.b64encode(p.read_bytes()).decode()}'" for p in sorted(dest.glob("*-loop.m4a"))]
(dest / "loops.js").write_text(
    "// Generated by design/konclui/sound/tools/prototype-assets.sh (konclui branch), do not edit: the -loop.m4a files as base64,\n"
    "// so features/sounds.js can decode them for Web Audio (gapless loops) on a file:// page, where a fetch is refused.\n"
    "window.KoruLoops={\n" + ",\n".join(rows) + "};\n")
print(f"{len(rows)} loops -> {dest / 'loops.js'}")
EOF
