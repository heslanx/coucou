def target_block(text: str, name: str) -> tuple[int, int]:
    start = text.index("\ntargets:\n")
    m = re.compile(rf"^  {name}:\n", re.M).search(text, start)
    if not m:
        raise SystemExit(f"project.yml: target {name} not found")
    nxt = re.compile(r"^  \S", re.M).search(text, m.end())
    return m.start(), nxt.start() if nxt else len(text)


def edit_project(text: str, log: list[str]) -> str:
    def in_target(name: str, fn):
        nonlocal text
        a, b = target_block(text, name)
        block = fn(text[a:b])
        text = text[:a] + block + text[b:]

    def mac_names(block: str) -> str:
        block = block.replace("CFBundleName: Coucou\n", f"CFBundleName: {APP}\n")
        block = block.replace("CFBundleDisplayName: Coucou\n", f"CFBundleDisplayName: {APP}\n")
        return re.sub(r'^(\s+NS\w+UsageDescription: )(".*")$',
                      lambda m: m.group(1) + json.dumps(brand(json.loads(m.group(2))), ensure_ascii=False),
                      block, flags=re.M)

    def github_build(block: str) -> str:
        block = mac_names(block)
        block = block.replace("CFBundleIdentifier: fr.louisraille.NotchBuddy\n", f"CFBundleIdentifier: {BUNDLE_ID}\n")
        block = block.replace("PRODUCT_BUNDLE_IDENTIFIER: fr.louisraille.NotchBuddy\n",
                              f"PRODUCT_BUNDLE_IDENTIFIER: {BUNDLE_ID}\n")
        block = block.replace("        PRODUCT_NAME: Coucou\n", f"        PRODUCT_NAME: {APP_ASCII}\n")
        if DEBUG_MARK not in block:
            block = block.replace("      configs:\n", "      configs:\n" + DEBUG_BLOCK + TEAM_NOTE, 1)
        return block

    before = text
    in_target("NotchBuddy", github_build)
    in_target("CoucouAppStore", mac_names)
    if text != before:
        log.append("NotchBuddy/project.yml: Mac targets renamed, GitHub build id/product/Debug signing")
    return text


