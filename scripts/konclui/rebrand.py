def brand(text: str, lang: str = "en") -> str:
    """User-visible text: Coucou -> Koncluí, Mochi -> Koru, with the grammar of `lang`."""
    parts = []
    last = 0
    for m in PROTECT.finditer(text):
        parts.append((False, text[last:m.start()]))
        parts.append((True, m.group(0)))
        last = m.end()
    parts.append((False, text[last:]))
    out = []
    for protected, chunk in parts:
        if not protected:
            for old, new in PHRASES:
                chunk = chunk.replace(old, new)
            for pat, rep in GRAMMAR.get(lang, []):
                chunk = re.sub(pat, rep, chunk)
            chunk = WAKE.sub(r"\1\2" + CHAR, chunk)
            chunk = re.sub(r"\bCoucou\b", APP, chunk)
            chunk = re.sub(r"\bMochi(s?)\b", CHAR + r"\1", chunk)
            for old, new in NAMES_LOCAL.get(lang, []):
                chunk = chunk.replace(old, new)
            for pat, rep in AGREEMENT.get(lang, []):
                chunk = re.sub(pat, rep, chunk)
            for pat, rep in TERMS.get(lang, []):
                chunk = re.sub(pat, rep, chunk)
        out.append(chunk)
    return "".join(out)


def swift_ids(text: str, rel: str) -> str:
    """Functional names inside Swift literals: support/log folders, hook and plugin names."""
    if rel not in KEEP_NOTCHBUDDY:
        text = re.sub(r"(?<!fr\.louisraille\.)\bNotchBuddy\b", APP_ASCII, text)
    if rel in LOWER_IDS:
        text = re.sub(r"\bcoucou\b(?!-mcp)", SLUG, text)
    return text


