# JSON files rewritten token by token, so the rest of the file keeps its layout

def json_tokens(text: str) -> list[tuple[int, int, tuple, bool]]:
    """(start, end, path, is_key) for every string token."""
    out: list[tuple[int, int, tuple, bool]] = []
    n = len(text)

    def ws(i: int) -> int:
        while i < n and text[i] in " \t\r\n":
            i += 1
        return i

    def string_end(i: int) -> int:
        j = i + 1
        while text[j] != '"':
            j += 2 if text[j] == "\\" else 1
        return j + 1

    def value(i: int, path: tuple) -> int:
        i = ws(i)
        c = text[i]
        if c == "{":
            i = ws(i + 1)
            if text[i] == "}":
                return i + 1
            while True:
                i = ws(i)
                e = string_end(i)
                key = json.loads(text[i:e])
                out.append((i, e, path, True))
                i = ws(e)
                i = value(i + 1, path + (key,))
                i = ws(i)
                if text[i] == ",":
                    i += 1
                    continue
                return i + 1
        if c == "[":
            i, k = ws(i + 1), 0
            if text[i] == "]":
                return i + 1
            while True:
                i = ws(value(i, path + (k,)))
                k += 1
                if text[i] == ",":
                    i += 1
                    continue
                return i + 1
        if c == '"':
            e = string_end(i)
            out.append((i, e, path, False))
            return e
        j = i
        while j < n and text[j] not in ",}] \t\r\n":
            j += 1
        return j

    value(0, ())
    return out


def json_value_end(text: str, i: int) -> int:
    """End of the JSON value that starts at text[i]."""
    if text[i] == '"':
        j = i + 1
        while text[j] != '"':
            j += 2 if text[j] == "\\" else 1
        return j + 1
    if text[i] in "{[":
        depth, j = 0, i
        while True:
            if text[j] == '"':
                j = json_value_end(text, j)
                continue
            if text[j] in "{[":
                depth += 1
            elif text[j] in "}]":
                depth -= 1
                if depth == 0:
                    return j + 1
            j += 1
    j = i
    while text[j] not in ",}] \t\r\n":
        j += 1
    return j


def json_cut(text: str, start: int, end: int) -> str:
    """Removes the member or element text[start:end], its line and one adjacent comma."""
    s = start
    while s > 0 and text[s - 1] in " \t":
        s -= 1
    k = end
    while k < len(text) and text[k] in " \t":
        k += 1
    if k < len(text) and text[k] == ",":
        k += 1
        if text.startswith("\n", k):
            k += 1
        return text[:s] + text[k:]
    p = s - 1
    while p >= 0 and text[p] in " \t\r\n":
        p -= 1
    return text[:p] + text[end:] if text[p] == "," else text[:s] + text[k:]


def remove_catalog_keys(text: str, keys: set[str]) -> tuple[str, int]:
    count = 0
    while True:
        hit = next(((a, b) for a, b, path, is_key in json_tokens(text)
                    if is_key and path == ("strings",) and json.loads(text[a:b]) in keys), None)
        if not hit:
            return text, count
        i = hit[1]
        while text[i] in " \t\r\n:":
            i += 1
        text, count = json_cut(text, hit[0], json_value_end(text, i)), count + 1


def remove_whatsnew_items(text: str, icon: str) -> tuple[str, int]:
    count = 0
    while True:
        tokens = json_tokens(text)
        item = next((path[:4] for a, b, path, is_key in tokens
                     if not is_key and len(path) == 5 and path[0] == "releases" and path[2] == "items"
                     and path[4] == "icon" and json.loads(text[a:b]) == icon), None)
        if not item:
            return text, count
        first_key = next(a for a, b, path, is_key in tokens if is_key and path == item)
        start = text.rfind("{", 0, first_key)
        text, count = json_cut(text, start, json_value_end(text, start)), count + 1


def rewrite_tokens(text: str, decide) -> tuple[str, int]:
    out, last, count = [], 0, 0
    for a, b, path, is_key in json_tokens(text):
        old = json.loads(text[a:b])
        new = decide(old, path, is_key)
        if new is None or new == old:
            continue
        count += 1
        out.append(text[last:a])
        out.append(json.dumps(new, ensure_ascii=False))
        last = b
    out.append(text[last:])
    return "".join(out), count


def catalog_decide(old: str, path: tuple, is_key: bool):
    if is_key and path == ("strings",):
        return brand(old, "en")
    if len(path) >= 4 and path[0] == "strings" and path[2] == "localizations" and path[-1] == "value":
        return brand(old, path[3])
    return None


def whatsnew_decide(old: str, path: tuple, is_key: bool):
    if is_key or len(path) < 2 or path[0] != "releases" or not isinstance(path[-1], str):
        return None
    return brand(old, path[-1])


