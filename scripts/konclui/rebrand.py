# Swift string literals

def literal_spans(src: str) -> list[tuple[int, int]]:
    """Spans of literal text in Swift source (no comments, no interpolated code)."""
    spans: list[tuple[int, int]] = []
    n = len(src)

    def code(i: int, in_interp: bool = False) -> int:
        depth = 0
        while i < n:
            c = src[i]
            if src.startswith("//", i):
                j = src.find("\n", i)
                i = n if j < 0 else j
                continue
            if src.startswith("/*", i):
                d, i = 1, i + 2
                while i < n and d:
                    if src.startswith("/*", i):
                        d, i = d + 1, i + 2
                    elif src.startswith("*/", i):
                        d, i = d - 1, i + 2
                    else:
                        i += 1
                continue
            if c in '#"':
                j, h = i, 0
                while j < n and src[j] == "#":
                    h, j = h + 1, j + 1
                if j < n and src[j] == '"':
                    i = string(j, h)
                    continue
                i = j if h else i + 1
                continue
            if in_interp:
                if c == "(":
                    depth += 1
                elif c == ")":
                    if depth == 0:
                        return i + 1
                    depth -= 1
            i += 1
        return i

    def string(j: int, h: int) -> int:
        quote = '"""' if src.startswith('"""', j) else '"'
        i = j + len(quote)
        close, esc, seg = quote + "#" * h, "\\" + "#" * h, i
        while i < n:
            if src.startswith(esc, i):
                k = i + len(esc)
                if k < n and src[k] == "(":
                    spans.append((seg, i))
                    i = code(k + 1, True)
                    seg = i
                    continue
                i = k + 1
                continue
            if src.startswith(close, i):
                spans.append((seg, i))
                return i + len(close)
            if quote == '"' and src[i] == "\n":
                spans.append((seg, i))
                return i
            i += 1
        return i

    code(0)
    return spans


