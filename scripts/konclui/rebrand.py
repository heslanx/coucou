def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="change nothing; exit 1 if a run would change files")
    ap.add_argument("--no-xcodegen", action="store_true", help="do not regenerate the Xcode project")
    args = ap.parse_args()

    log: list[str] = []
    stale: list[str] = []
    pending: dict[Path, str] = {}

    def read(rel: str) -> str:
        p = ROOT / rel
        return pending.get(p, p.read_text(encoding="utf-8"))

    def stage(rel: str, text: str):
        p = ROOT / rel
        if text != p.read_text(encoding="utf-8"):
            pending[p] = text

    # 1. project.yml
    stage("NotchBuddy/project.yml", edit_project(read("NotchBuddy/project.yml"), log))

    # 2. fixed edits
    for rel, old, new in FIXED:
        text = read(rel)
        if old in text:
            stage(rel, text.replace(old, new))
            log.append(f"{rel}: {old!r} -> {new!r}")
        elif new not in text:
            stale.append(f"{rel}: neither {old!r} nor {new!r} found")
    for rel, pattern, repl in CODE:
        text = read(rel)
        new, n = re.subn(pattern, repl, text)
        if n:
            stage(rel, new)
            log.append(f"{rel}: {n} x {pattern!r}")
        elif repl.split("(")[0] not in text:
            stale.append(f"{rel}: {pattern!r} matches nothing and {repl!r} is absent")
    for rel, anchor, block in INSERTS:
        text = read(rel)
        if block in text:
            continue
        if anchor in text:
            stage(rel, text.replace(anchor, block + anchor, 1))
            log.append(f"{rel}: inserted {block.strip().splitlines()[0]!r}")
        else:
            stale.append(f"{rel}: anchor {anchor!r} not found")
    mcp = read(MCP_SCRIPT)
    mcp_new, names = re.subn(r"\bCoucou\b", APP, mcp)
    if names:
        stage(MCP_SCRIPT, mcp_new)
        log.append(f"{MCP_SCRIPT}: {names} names")

    # 3. Swift literals
    total = 0
    for f in swift_files():
        rel = f.relative_to(NB / "Sources").as_posix()
        full = f.relative_to(ROOT).as_posix()
        new, count = edit_swift(read(full), rel)
        if count:
            stage(full, new)
            total += count
            log.append(f"{full}: {count} literals")

    # 4-5. catalog and what's new: the coffee goes, then the names
    for rel, remove, what in (("NotchBuddy/Resources/Localizable.xcstrings",
                               lambda t: remove_catalog_keys(t, REMOVE_KEYS), "coffee keys"),
                              ("NotchBuddy/Resources/whats-new.json",
                               lambda t: remove_whatsnew_items(t, REMOVE_ITEM_ICON), "coffee items")):
        new, count = remove(read(rel))
        json.loads(new)
        if count:
            stage(rel, new)
            log.append(f"{rel}: removed {count} {what}")
    keys_before = len(json.loads(read("NotchBuddy/Resources/Localizable.xcstrings"))["strings"])
    for rel, decide in (("NotchBuddy/Resources/Localizable.xcstrings", catalog_decide),
                        ("NotchBuddy/Resources/whats-new.json", whatsnew_decide)):
        text = read(rel)
        new, count = rewrite_tokens(text, decide)
        json.loads(new)
        if count:
            stage(rel, new)
            log.append(f"{rel}: {count} strings")
    if len(json.loads(read("NotchBuddy/Resources/Localizable.xcstrings"))["strings"]) != keys_before:
        raise SystemExit("Localizable.xcstrings: a renamed key collides with an existing one")

    # 6. what the screens say (copy_rules): the catalog's COPY, SUBS, DASHES and PATHS, then the permission prompts
    catalog_rel = "NotchBuddy/Resources/Localizable.xcstrings"
    new, count = copy_rules.apply(read(catalog_rel), stale)
    json.loads(new)
    if count:
        stage(catalog_rel, new)
        log.append(f"{catalog_rel}: {count} entries rewritten by the copy rules")
    info_text = copy_rules.info_plist_catalog()
    info_path = ROOT / INFO_PLIST_CATALOG
    if not info_path.exists() or info_path.read_text(encoding="utf-8") != info_text:
        pending[info_path] = info_text
        log.append(f"{INFO_PLIST_CATALOG}: the permission prompts in 14 languages")

    for line in log:
        print("  " + line)
    for line in stale:
        print("  STALE " + line)
    print(f"rebrand: {len(pending)} files {'would change' if args.check else 'changed'}"
          f" ({total} Swift literals), {len(stale)} stale rules")

    if args.check:
        return 1 if pending else 0
    for p, text in pending.items():
        p.write_text(text, encoding="utf-8")
    if pending and not args.no_xcodegen:
        if shutil.which("xcodegen"):
            subprocess.run(["xcodegen"], cwd=NB, check=True, stdout=subprocess.DEVNULL)
            print("rebrand: xcodegen regenerated the project and Info.plist files")
        else:
            print("rebrand: xcodegen not found; run `cd NotchBuddy && xcodegen` before building")
    return 0


if __name__ == "__main__":
    sys.exit(main())
